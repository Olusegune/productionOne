// Smoke drive of the installed or built app through WebView2's debug port. Needs: npm i --no-save playwright-core.
// Start the app first:  $env:WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS='--remote-debugging-port=9222'; & .\ProductionOne.exe   then: node scripts/live/smoke-ui.mjs
import { chromium } from 'playwright-core'
const browser = await chromium.connectOverCDP('http://127.0.0.1:9222')
const page = browser.contexts()[0].pages()[0]
const errors = []
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 200)) })
page.on('pageerror', (e) => errors.push('PAGEERR ' + e.message.slice(0, 200)))
const log = (...a) => console.log(...a)
const nav = (name) => page.locator('.po-steps, nav, header').getByRole('button', { name, exact: true }).first()
const shot = (n) => page.screenshot({ path: `./${n}.png` })
await page.waitForTimeout(1500)
log('title:', await page.title())
await page.getByRole('button', { name: 'Design', exact: true }).nth(0).click().catch(() => {})
// the segmented top bar button
await page.locator('button', { hasText: /^Design$/ }).last().click()
await page.waitForSelector('.sheet-studio', { timeout: 8000 })
log('sheet studio:', await page.locator('.ss-status').innerText(), '| folds:', await page.locator('.fold').count(), '| image quality button:', await page.getByRole('button', { name: /Image quality/ }).count())
await shot('p-design')
await page.locator('button', { hasText: /^Direct/ }).first().click()
const on = page.getByRole('button', { name: /Turn on the Director/ })
if (await on.count()) await on.click()
await page.getByRole('button', { name: /Plan all scenes/ }).click()
await page.waitForSelector('.dr-card')
log('director cards:', await page.locator('.dr-card').count(), '| inspector folds:', await page.locator('.dr-inspector .fold').count())
await page.locator('.dr-card').first().getByRole('button', { name: 'More actions' }).click()
log('overflow menu items:', await page.locator('.dr-menu [role=menuitem]').count())
await page.keyboard.press('Escape')
await page.locator('.dr-card .dr-thumb').first().focus()
await page.keyboard.press('ArrowRight')
log('keyboard selected card:', await page.locator('.dr-card.on').getAttribute('data-shot'))
await page.getByRole('button', { name: 'Large storyboard' }).click()
log('large layout class:', await page.locator('.dr-cards').getAttribute('class'))
await shot('p-direct')
await page.locator('button', { hasText: /^Deliver/ }).first().click()
await page.waitForSelector('.dc')
log('deliver:', (await page.locator('.dc-summary').innerText()).replace(/\n+/g, ' | ').slice(0, 220))
log('verified export disabled:', await page.getByRole('button', { name: /Export verified package/ }).isDisabled())
await shot('p-deliver')
log('console errors:', errors.length, errors.slice(0, 5))
console.log('DONE30')
await browser.close()
